"""Bundle the shared screen styles in a predictable order; no network or build tools."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "static" / "css"
SOURCES = ["components.css", "responsive.css", "premium.css", "scanner.css"]


def build():
    content = "/* Generated by scripts/build_styles.py. Edit source styles, then rebuild. */\n"
    for source in SOURCES:
        content += f"\n/* ===== {source} ===== */\n" + (CSS / source).read_text(encoding="utf-8")
    (CSS / "app.css").write_text(content, encoding="utf-8")


if __name__ == "__main__":
    build()
